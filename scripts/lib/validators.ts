import { Ajv2020 } from "ajv/dist/2020.js";
import { Schema } from "effect";
import standaloneCode from "ajv/dist/standalone/index.js";

type SchemasByModule = Readonly<Record<string, Readonly<Record<string, Schema.Constraint>>>>;

interface Entry {
  readonly module: string;
  readonly name: string;
  readonly schema: Schema.Constraint;
}

interface GeneratedValidators {
  readonly declarations: string;
  readonly javascript: string;
  readonly requires: readonly string[];
}

const HEADER = "// Generated by scripts/generate-validators.ts from the backend's response Schemas. Do not edit.\n";
const UNICODE_DEPRECATION = "DEPRECATED: option unicode.";

function entriesOf(schemas: SchemasByModule): readonly Entry[] {
  return Object.entries(schemas).flatMap(
    ([module, named]: readonly [string, Readonly<Record<string, Schema.Constraint>>]) =>
      Object.entries(named).map(([name, schema]: readonly [string, Schema.Constraint]) => ({ module, name, schema })),
  );
}

function warnUnlessUnicodeOption(...warning: readonly unknown[]): void {
  const [message] = warning;
  if (!String(message).startsWith(UNICODE_DEPRECATION)) {
    console.warn(...warning);
  }
}

function compile(entries: readonly Entry[]): string {
  const ajv = new Ajv2020({
    allErrors: false,
    code: { esm: true, lines: true, source: true },
    logger: { error: console.error, log: console.log, warn: warnUnlessUnicodeOption },
    strict: true,
    // oxlint-disable-next-line typescript/no-deprecated
    unicode: false,
  });
  for (const { name, schema } of entries) {
    const document = Schema.toJsonSchemaDocument(schema);
    ajv.addSchema(Object.fromEntries([...Object.entries(document.schema), ["$defs", document.definitions]]), name);
  }
  return standaloneCode(ajv, Object.fromEntries(entries.map(({ name }) => [`is${name}`, name])));
}

function entryPointOf(module: string): string {
  if (module.endsWith(".ts")) {
    return module;
  }
  return `${module}/index.ts`;
}

function typeImport([module, group]: readonly [string, readonly Entry[] | undefined]): string {
  const names = (group ?? []).map(({ name }) => name).join(", ");
  return `import type { ${names} } from "../../../${entryPointOf(module)}";`;
}

function declare(entries: readonly Entry[]): string {
  const guards = entries.map(({ name }) => `export declare function is${name}(data: unknown): data is ${name};`);
  const typeImports = Object.entries(Object.groupBy(entries, ({ module }) => module)).map(
    (group: readonly [string, readonly Entry[] | undefined]) => typeImport(group),
  );
  return `${HEADER}${[...typeImports, "", ...guards].join("\n")}\n`;
}

function requiresIn(javascript: string): readonly string[] {
  return Array.from(javascript.matchAll(/require\(\s*(?<module>"[^"]*"|'[^']*')/gu), ([, module]: readonly string[]) =>
    String(module),
  );
}

function generateValidators(schemas: SchemasByModule): GeneratedValidators {
  const entries = entriesOf(schemas);
  const javascript = `${HEADER}${compile(entries)}\n`;
  return { declarations: declare(entries), javascript, requires: requiresIn(javascript) };
}

export { generateValidators };

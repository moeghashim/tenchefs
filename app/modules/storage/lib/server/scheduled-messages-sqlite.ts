import { Effect, Predicate, Schema } from "effect";
import type { ScheduledMessagesSection, ScheduledRecords, StoredScheduledMessage } from "./scheduled-messages.ts";
import {
  isScheduledMessageId,
  scheduledMessagePauseReasons,
  scheduledMessageStatuses,
  scheduledRunOutcomes,
} from "../../../scheduled-messages/index.ts";
import { IsoTimeSchema } from "../../../time/server.ts";
import type { SqlDatabase } from "./adapters/sql-database.ts";
import type { StorageUnavailable } from "./errors.ts";
import { appenderOf } from "./messages-sqlite.ts";
import { isChannelName } from "../../../channels/index.ts";
import { isIdentityName } from "../../../identities/index.ts";
import { isMessageId } from "../../../messages/index.ts";
import { scheduledMessagesOn } from "./scheduled-messages.ts";
import { unreadable } from "./errors.ts";

type Fails<Value> = Effect.Effect<Value, StorageUnavailable>;

const POSTGRES_SCHEDULED_MESSAGES_MIGRATION: readonly string[] = [
  `CREATE TABLE scheduled_messages (
     id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     channel text COLLATE "C" NOT NULL REFERENCES channels (name),
     creator text COLLATE "C" NOT NULL REFERENCES identities (name),
     text text COLLATE "C" NOT NULL,
     cron text COLLATE "C",
     run_at text COLLATE "C",
     time_zone text COLLATE "C" NOT NULL,
     status text COLLATE "C" NOT NULL CHECK (status IN ('active', 'paused', 'finished')),
     paused_because text COLLATE "C" CHECK (paused_because IN ('creator_deactivated')),
     runs_from text COLLATE "C" NOT NULL,
     last_run_due text COLLATE "C",
     last_run_outcome text COLLATE "C" CHECK (last_run_outcome IN ('posted', 'skipped')),
     last_run_message bigint,
     created_at text COLLATE "C" NOT NULL,
     updated_at text COLLATE "C" NOT NULL,
     deleted_at text COLLATE "C",
     CHECK ((cron IS NULL) <> (run_at IS NULL))
   )`,
  "CREATE INDEX scheduled_messages_by_channel ON scheduled_messages (channel, id)",
  "CREATE INDEX scheduled_messages_by_creator ON scheduled_messages (creator)",
  "ALTER TABLE messages ADD COLUMN scheduled_message_id bigint",
];

const COLUMNS = `id, channel, creator, text, cron, run_at, time_zone, status, paused_because, runs_from,
  last_run_due, last_run_outcome, last_run_message, created_at, updated_at`;

const INSERT = `INSERT INTO scheduled_messages
  (channel, creator, text, cron, run_at, time_zone, status, runs_from, created_at, updated_at)
  VALUES (?, ?, ?, ?, ?, ?, 'active', ?, ?, ?) RETURNING ${COLUMNS}`;

const FIND = `SELECT ${COLUMNS} FROM scheduled_messages WHERE id = ? AND deleted_at IS NULL`;
const LIST_ALL = `SELECT ${COLUMNS} FROM scheduled_messages WHERE deleted_at IS NULL ORDER BY id`;
const LIST_CHANNEL = `SELECT ${COLUMNS} FROM scheduled_messages WHERE deleted_at IS NULL AND channel = ? ORDER BY id`;
const SAVE = `UPDATE scheduled_messages SET text = ?, cron = ?, run_at = ?, time_zone = ?, status = ?, paused_because = ?, runs_from = ?, last_run_due = ?,
  last_run_outcome = ?, last_run_message = ?, updated_at = ? WHERE id = ?`;
const CHANNEL_EXISTS = "SELECT 1 AS found FROM channels WHERE name = ?";
const MARK_DELETED = "UPDATE scheduled_messages SET deleted_at = ? WHERE id = ?";

const MessageIdColumn = Schema.Int.pipe(Schema.refine(isMessageId));

const ScheduleRow = Schema.Struct({
  channel: Schema.String.pipe(Schema.refine(isChannelName)),
  created_at: IsoTimeSchema,
  creator: Schema.String.pipe(Schema.refine(isIdentityName)),
  cron: Schema.NullOr(Schema.String),
  id: Schema.Int.pipe(Schema.refine(isScheduledMessageId)),
  last_run_due: Schema.NullOr(IsoTimeSchema),
  last_run_message: Schema.NullOr(MessageIdColumn),
  last_run_outcome: Schema.NullOr(Schema.Literals(scheduledRunOutcomes)),
  paused_because: Schema.NullOr(Schema.Literals(scheduledMessagePauseReasons)),
  run_at: Schema.NullOr(IsoTimeSchema),
  runs_from: IsoTimeSchema,
  status: Schema.Literals(scheduledMessageStatuses),
  text: Schema.String,
  time_zone: Schema.String,
  updated_at: IsoTimeSchema,
});

type ScheduleRowType = typeof ScheduleRow.Type;

function lastRunOf(row: ScheduleRowType): StoredScheduledMessage["lastRun"] {
  if (row.last_run_due === null || row.last_run_outcome === null) {
    return null;
  }
  return { due: row.last_run_due, messageId: row.last_run_message, outcome: row.last_run_outcome };
}

function scheduleOf(row: ScheduleRowType): StoredScheduledMessage {
  return {
    at: row.run_at,
    channel: row.channel,
    createdAt: row.created_at,
    creator: row.creator,
    cron: row.cron,
    id: row.id,
    lastRun: lastRunOf(row),
    pausedBecause: row.paused_because,
    runsFrom: row.runs_from,
    status: row.status,
    text: row.text,
    timeZone: row.time_zone,
    updatedAt: row.updated_at,
  };
}

function scheduleRow(row: unknown): Fails<StoredScheduledMessage> {
  return Schema.decodeUnknownEffect(ScheduleRow)(row).pipe(
    Effect.mapBoth({ onFailure: unreadable, onSuccess: scheduleOf }),
  );
}

function maybeScheduleRow(row: unknown): Fails<StoredScheduledMessage | undefined> {
  if (Predicate.isUndefined(row)) {
    return Effect.undefined;
  }
  return scheduleRow(row);
}

function scheduleRows(rows: readonly unknown[]): Fails<readonly StoredScheduledMessage[]> {
  return Effect.forEach(rows, scheduleRow, { concurrency: 1 });
}

function lastRunColumns(
  lastRun: StoredScheduledMessage["lastRun"],
): readonly [string | null, string | null, number | null] {
  if (lastRun === null) {
    return [null, null, null];
  }
  return [lastRun.due, lastRun.outcome, lastRun.messageId];
}

function sqlRecords(db: SqlDatabase): ScheduledRecords {
  return {
    channelExists: (channel) => Effect.map(db.get(CHANNEL_EXISTS, channel), Predicate.isNotUndefined),
    find: (id) => Effect.flatMap(db.get(FIND, id), maybeScheduleRow),
    insert: ({ at, channel, createdAt, creator, cron, text, timeZone }) =>
      Effect.flatMap(
        db.get(INSERT, channel, creator, text, cron, at, timeZone, createdAt, createdAt, createdAt),
        scheduleRow,
      ),
    list: (channel) => {
      if (Predicate.isUndefined(channel)) {
        return Effect.flatMap(db.all(LIST_ALL), scheduleRows);
      }
      return Effect.flatMap(db.all(LIST_CHANNEL, channel), scheduleRows);
    },
    markDeleted: (id, at) => db.run(MARK_DELETED, at, id),
    save: ({ at, cron, id, lastRun, pausedBecause, runsFrom, status, text, timeZone, updatedAt }) =>
      db.run(
        SAVE,
        text,
        cron,
        at,
        timeZone,
        status,
        pausedBecause,
        runsFrom,
        ...lastRunColumns(lastRun),
        updatedAt,
        id,
      ),
  };
}

function sqlScheduledMessages(db: SqlDatabase): ScheduledMessagesSection {
  return scheduledMessagesOn({
    appendMessage: appenderOf(db),
    atomically: db.transaction,
    records: sqlRecords(db),
  });
}

export { POSTGRES_SCHEDULED_MESSAGES_MIGRATION, sqlScheduledMessages };
